export const normalizeCategory = (cat: string): string => {
  if (!cat) return 'frozen_food';
  const c = cat.toLowerCase().trim();
  if (c === 'sayur' || c === 'sayuran') return 'sayur';
  if (c === 'buah' || c === 'buah_buahan') return 'buah';
  if (c === 'bahan_kue') return 'bahan_kue';
  if (c === 'plastik' || c === 'plastik_kemasan') return 'plastik';
  if (c === 'bumbu_saus' || c === 'saus_sambal' || c === 'bumbu_dapur') return 'bumbu_saus';
  if (
    c === 'nugget_sosis' ||
    c === 'daging_ayam' ||
    c === 'dimsum_siomay' ||
    c === 'seafood' ||
    c === 'kentang_sayur' ||
    c === 'frozen_lainnya' ||
    c === 'frozen_food'
  ) {
    return 'frozen_food';
  }
  return cat;
};

